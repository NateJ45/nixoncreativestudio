// Generates src/data/us-dots.json, the dot map behind About's "Based in Cincinnati" section
// (src/components/ClientMap.astro). Run it again only to change the grid or the states drawn.
//
// The geometry tools are NOT dependencies of this repo. Install them somewhere else and pass that
// folder in:
//
//   npm i --prefix <dir> us-atlas@3.0.1 topojson-client@3.1.0 topojson-simplify@3.0.3 d3-geo@3.1.1
//   node scripts/tools/us-dots.mjs <dir>/node_modules
//
// It reads us-atlas's states-albers-10m.json (already projected with geoAlbersUsa at scale 1300,
// 975 by 610), drops Alaska and Hawaii, and lays a hex grid of dots over the lower 48. Every dot
// that falls inside a state keeps that state's FIPS code. It also writes the outline of each state
// in OUTLINED, a point for Cincinnati, and two simplified line drawings of the whole map: the
// borders between states and the outline of the lower 48 (simplified, so the page stays light),
// all in the same grid units (one dot step = 10 units).
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';

const dir = process.argv[2];
if (!dir)
  throw new Error('Pass the node_modules folder that holds us-atlas, topojson-client and d3-geo');
const req = createRequire(join(dir, 'noop.js'));
const topo = JSON.parse(readFileSync(req.resolve('us-atlas/states-albers-10m.json'), 'utf8'));
const { feature, mesh } = await import(pathToFileURL(req.resolve('topojson-client')).href);
const simp = await import(pathToFileURL(req.resolve('topojson-simplify')).href);
const d3 = await import(pathToFileURL(req.resolve('d3-geo')).href);

// One dot step in albers units. Smaller means more dots and a heavier page.
const S = 10.5;
const SKIP = new Set(['02', '15']); // Alaska, Hawaii
const OUTLINED = ['39', '18', '37', '45']; // Ohio, Indiana, North Carolina, South Carolina
const CINCINNATI = [-84.512, 39.103];

const states = feature(topo, topo.objects.states).features.filter((f) => !SKIP.has(f.id));

// Bounds of the lower 48 in albers units.
const planar = d3.geoPath();
let [[x0, y0], [x1, y1]] = planar.bounds({ type: 'FeatureCollection', features: states });
x0 -= S;
y0 -= S;
x1 += S;
y1 += S;

// Planar point-in-polygon over a feature's rings (even-odd, so holes work).
function inside(geom, x, y) {
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  let hit = false;
  for (const rings of polys)
    for (const ring of rings)
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i];
        const [xj, yj] = ring[j];
        if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
      }
  return hit;
}

const DY = (S * Math.sqrt(3)) / 2;
const dots = [];
for (let row = 0; y0 + row * DY <= y1; row++) {
  const y = y0 + row * DY;
  for (let col = 0; x0 + col * S <= x1; col++) {
    const x = x0 + col * S + (row % 2 ? S / 2 : 0);
    const st = states.find((f) => inside(f.geometry, x, y));
    if (st) dots.push([col, row, Number(st.id)]);
  }
}

// Grid units: one dot step = 10.
const k = 10 / S;
const toGrid = d3
  .geoIdentity()
  .scale(k)
  .translate([-x0 * k, -y0 * k]);
const gridPath = d3.geoPath(toGrid).digits(1);
const outlines = {};
const centers = {};
for (const id of OUTLINED) {
  const f = states.find((s) => s.id === id);
  outlines[Number(id)] = gridPath(f);
  centers[Number(id)] = gridPath.centroid(f).map((n) => Math.round(n * 10) / 10);
}
const albers = d3.geoAlbersUsa().scale(1300).translate([487.5, 305]);
const [cx, cy] = albers(CINCINNATI);
const hub = [Math.round((cx - x0) * k * 10) / 10, Math.round((cy - y0) * k * 10) / 10];

// The line drawings, from a simplified copy (weights are areas in square albers units). Interior
// borders are the arcs two states share; the outline is the arcs only one state uses.
// 2.5 keeps the two drawings to about 21 KB of path data; pass a second argument to try another.
const MIN_WEIGHT = Number(process.argv[3] || 2.5);
const lite = simp.simplify(simp.presimplify(JSON.parse(JSON.stringify(topo))), MIN_WEIGHT);
const lower48 = {
  type: 'GeometryCollection',
  geometries: lite.objects.states.geometries.filter((g) => !SKIP.has(g.id)),
};
const borders = gridPath(mesh(lite, lower48, (a, b) => a !== b));
const coast = gridPath(mesh(lite, lower48, (a, b) => a === b));

const out = {
  note: 'Generated by scripts/tools/us-dots.mjs from us-atlas states-albers-10m. Do not edit by hand.',
  w: Math.ceil((x1 - x0) * k),
  h: Math.ceil((y1 - y0) * k),
  step: 10,
  // [column, row, state FIPS]. x = column * 10 (+ 5 on odd rows), y = row * 10 * sqrt(3) / 2.
  dots,
  outlines,
  centers,
  hub,
  borders,
  coast,
};
writeFileSync(new URL('../../src/data/us-dots.json', import.meta.url), JSON.stringify(out) + '\n');
console.log(`${dots.length} dots, ${out.w} by ${out.h}`);
