// Safe to edit.
/* ============================================================================
   build-course-line.mjs: the Stone Steps course data for CourseLine.astro
   ============================================================================
   Usage (LOCAL ONLY, from this repo's root):

     node scripts/build-course-line.mjs
     node scripts/build-course-line.mjs --source <path to course-profile.json>

   Reads the real course trace from the sibling Stone Steps repo,

     ../../clients/stonesteps-50k/scripts/data/course-profile.json

   (one row per GPS point of David Corfman's recorded run of the course, with
   elevation sampled from USGS 1-meter LiDAR by that repo's own pipeline),
   keeps about 600 of its points and writes

     src/data/stone-steps-course.ts

   which IS committed. CI cannot read a sibling repo, so the build never runs
   this script; it only imports the generated file. Re-run it when the Stone
   Steps repo re-measures the course, look at the diff, and commit both.

   Every number in the output comes from the source file. Nothing is smoothed,
   interpolated or rounded beyond the precision listed below: the kept points
   are real points of the trace, chosen at evenly spaced indexes, and the
   first and last points are always kept.

   Source row: [lon, lat, elevation ft, mile, grade %, loop number].
   ============================================================================ */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const argSource = process.argv.indexOf('--source');
const source =
  argSource > -1
    ? resolve(process.argv[argSource + 1])
    : resolve(root, '../../clients/stonesteps-50k/scripts/data/course-profile.json');
const out = resolve(root, 'src/data/stone-steps-course.ts');

/** How many points to keep. About 600 keeps the drawn line faithful at any
    size the study shows it, and a 0.1 mi scrub step always lands within about
    0.05 mi of a real point, while the page stays well under its 150 KB HTML
    budget. */
const TARGET = 600;

let raw;
try {
  raw = JSON.parse(readFileSync(source, 'utf8'));
} catch (err) {
  console.error(`build-course-line: cannot read ${source}`);
  console.error('  This script runs locally, next to a checkout of the stonesteps-50k repo.');
  console.error(`  ${err.message}`);
  process.exit(1);
}

const rows = raw?.points;
if (!Array.isArray(rows) || rows.length < 2) {
  console.error('build-course-line: the source has no `points` array.');
  process.exit(1);
}

// Check every row before using any of it, so a changed format fails loudly
// instead of drawing a wrong line.
rows.forEach((r, i) => {
  const ok = Array.isArray(r) && r.length >= 6 && r.slice(0, 6).every((v) => Number.isFinite(v));
  if (!ok) {
    console.error(`build-course-line: row ${i} is not [lon, lat, ft, mile, grade, loop].`);
    process.exit(1);
  }
  if (i > 0 && r[3] < rows[i - 1][3]) {
    console.error(`build-course-line: mile goes backwards at row ${i}.`);
    process.exit(1);
  }
});

// Evenly spaced indexes, first and last included, no repeats.
const n = rows.length;
const keep = Math.min(TARGET, n);
const picked = [];
for (let k = 0; k < keep; k++) {
  const idx = Math.round((k * (n - 1)) / (keep - 1));
  if (picked[picked.length - 1] !== idx) picked.push(idx);
}

const points = picked.map((idx) => {
  const [lon, lat, ft, mile, grade, loop] = rows[idx];
  return [
    +lon.toFixed(5),
    +lat.toFixed(5),
    Math.round(ft),
    +mile.toFixed(2),
    +grade.toFixed(1),
    loop,
  ];
});

// Summary figures, from ALL source rows (not just the kept ones).
const ft = rows.map((r) => r[2]);
const lowFt = Math.round(Math.min(...ft));
const highFt = Math.round(Math.max(...ft));
const totalMiles = +rows[n - 1][3].toFixed(2);

// Loops: where each one starts on the trace, from the loop column.
const loops = [];
for (const r of rows) {
  const last = loops[loops.length - 1];
  if (!last || last.loop !== r[5]) loops.push({ loop: r[5], startMile: +r[3].toFixed(2) });
}

const lon = rows.map((r) => r[0]);
const lat = rows.map((r) => r[1]);
const bounds = {
  west: Math.min(...lon),
  east: Math.max(...lon),
  south: Math.min(...lat),
  north: Math.max(...lat),
};

const file = `// GENERATED by scripts/build-course-line.mjs. Do not edit by hand.
// Source: stonesteps-50k/scripts/data/course-profile.json (${n} points: David
// Corfman's recorded run of the course, elevation from USGS 1-meter LiDAR).
// Re-run the script locally and commit this file when the source changes.

/** One kept point of the trace: [lon, lat, elevation ft, mile, grade %, loop]. */
export type CoursePoint = [number, number, number, number, number, number];

export const courseSource = {
  file: 'stonesteps-50k/scripts/data/course-profile.json',
  sourcePoints: ${n},
  keptPoints: ${points.length},
} as const;

/** Miles along the recorded run (the GPS trace, not the race's published distance). */
export const courseMiles = ${totalMiles};

/** Lowest and highest elevation on the trace, in feet. */
export const courseElevation = { lowFt: ${lowFt}, highFt: ${highFt} } as const;

/** The trace's bounding box, in degrees. */
export const courseBounds = ${JSON.stringify(bounds)} as const;

/** Where each loop starts, in miles along the trace. */
export const courseLoops: ReadonlyArray<{ loop: number; startMile: number }> = ${JSON.stringify(loops)};

export const coursePoints: ReadonlyArray<CoursePoint> = [
${points.map((p) => `  ${JSON.stringify(p)},`).join('\n')}
];
`;

writeFileSync(out, file);
console.log(
  `build-course-line: ${points.length} of ${n} points, ${loops.length} loops, ${totalMiles} mi, ${lowFt} to ${highFt} ft -> src/data/stone-steps-course.ts`,
);
