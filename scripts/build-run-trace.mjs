// Safe to edit.
/* ============================================================================
   build-run-trace.mjs: my Flying Pig 10K for the Running card on About
   ============================================================================
   Usage (LOCAL ONLY, from this repo's root):

     node scripts/build-run-trace.mjs --gpx <activity.gpx> --csv <activity.csv>

   Reads a Garmin Connect export of one run (the GPX for the track, the splits
   CSV for the summary and per-mile laps), keeps a point every 40 meters or so
   and writes

     src/data/flying-pig-10k.ts

   which IS committed. The raw export is not: it carries heart rate and exact
   timestamps for every second, and the card needs none of that. Re-run this
   only if the run changes, look at the diff, and commit the output.

   What goes in: the route (lon, lat), elevation (GPS altitude in feet, lightly
   smoothed so the profile is not a sawtooth) and miles along the route. The
   headline numbers (distance, time, pace, climb) are Garmin's own summary row,
   not recomputed here, so they match the watch.
   ============================================================================ */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const arg = (name) => {
  const i = process.argv.indexOf(name);
  if (i < 0) throw new Error(`Missing ${name} <path>`);
  return resolve(process.argv[i + 1]);
};
const gpx = readFileSync(arg('--gpx'), 'utf8');
const csv = readFileSync(arg('--csv'), 'utf8');

/* ---- Track points ---- */
const raw = [
  ...gpx.matchAll(/<trkpt lat="([-\d.]+)" lon="([-\d.]+)">\s*<ele>([-\d.]+)<\/ele>/g),
].map((m) => ({ lat: +m[1], lon: +m[2], ele: +m[3] * 3.28084 }));
if (raw.length < 100) throw new Error(`Only ${raw.length} track points found`);

const R = 3958.8; // miles
const rad = (d) => (d * Math.PI) / 180;
const hav = (a, b) => {
  const dLat = rad(b.lat - a.lat);
  const dLon = rad(b.lon - a.lon);
  const h =
    Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};
let mi = 0;
raw.forEach((p, i) => {
  if (i) mi += hav(raw[i - 1], p);
  p.mi = mi;
});

// A centred moving average over about 15 seconds of altitude: GPS altitude jitters a few feet.
const W = 7;
raw.forEach((p, i) => {
  const s = raw.slice(Math.max(0, i - W), i + W + 1);
  p.sm = s.reduce((t, q) => t + q.ele, 0) / s.length;
});

const STEP = 0.025; // miles, about 40 m
const kept = [raw[0]];
for (const p of raw) if (p.mi - kept.at(-1).mi >= STEP) kept.push(p);
if (kept.at(-1) !== raw.at(-1)) kept.push(raw.at(-1));

const points = kept.map((p) => [
  +p.lon.toFixed(5),
  +p.lat.toFixed(5),
  Math.round(p.sm),
  +p.mi.toFixed(3),
]);
const lats = points.map((p) => p[1]);
const lons = points.map((p) => p[0]);
const eles = points.map((p) => p[2]);

/* ---- Garmin's summary and laps ---- */
const rows = csv
  .trim()
  .split(/\r?\n/)
  .map((l) => [...l.matchAll(/"([^"]*)"/g)].map((m) => m[1]));
const head = rows[0];
const col = (row, name) => row[head.indexOf(name)];
const summary = rows.find((r) => r[0] === 'Summary');
if (!summary) throw new Error('No Summary row in the CSV');
const laps = rows
  .slice(1)
  .filter((r) => r[0] !== 'Summary')
  .map((r) => ({ miles: +col(r, 'Distance mi'), pace: col(r, 'Avg Pace min/mi') }));

const stats = {
  miles: +col(summary, 'Distance mi'),
  time: col(summary, 'Time'),
  pace: col(summary, 'Avg Pace min/mi'),
  climbFt: +col(summary, 'Total Ascent ft'),
};

const out = `// GENERATED by scripts/build-run-trace.mjs. Do not edit by hand.
// Source: my Garmin Connect export of the Flying Pig 10K (GPX track and splits CSV).
// ${raw.length} recorded points, ${points.length} kept. The raw export is not committed.

/** Garmin's own summary of the run. */
export const runStats = ${JSON.stringify(stats)} as const;

/** Garmin's laps: one per mile, the last one the leftover quarter. Pace is min:sec per mile. */
export const runSplits: ReadonlyArray<{ miles: number; pace: string }> = ${JSON.stringify(laps)};

/** Lowest and highest (smoothed) elevation on the route, in feet. */
export const runElevation = { lowFt: ${Math.min(...eles)}, highFt: ${Math.max(...eles)} } as const;

/** The route's bounding box, in degrees. */
export const runBounds = {
  west: ${Math.min(...lons)},
  east: ${Math.max(...lons)},
  south: ${Math.min(...lats)},
  north: ${Math.max(...lats)},
} as const;

/** One kept point: [lon, lat, elevation ft, mile]. */
export const runPoints: ReadonlyArray<[number, number, number, number]> = ${JSON.stringify(points)};
`;
const dest = resolve(root, 'src/data/flying-pig-10k.ts');
writeFileSync(dest, out);
console.log(`Wrote ${dest}: ${points.length} points, ${(out.length / 1024).toFixed(1)} KB`);
